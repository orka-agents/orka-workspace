#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/../providers"
controller_gen="${1:?absolute controller-gen path is required}"
provider_name="${2:?provider name is required}"
case "$provider_name" in sandbox|substrate) ;; *) echo "unsupported provider API directory" >&2; exit 1 ;; esac
generated_dir="$(mktemp -d)"
trap 'rm -rf "$generated_dir"' EXIT
"$controller_gen" crd:allowDangerousTypes=true "paths=./$provider_name/api/..." "output:crd:artifacts:config=$generated_dir/crds"
"$controller_gen" object:headerFile=../hack/boilerplate.go.txt "paths=./$provider_name/api/..." "output:object:dir=$generated_dir/deepcopy"
diff -ru "$provider_name/config/crd" "$generated_dir/crds"
diff -u "$provider_name/api/v1alpha1/zz_generated.deepcopy.go" "$generated_dir/deepcopy/zz_generated.deepcopy.go"

if [[ "$provider_name" == substrate ]]; then
  # The vendored native protocol must be the untouched pinned upstream source,
  # and its bindings must name the pinned generators. Full regeneration needs
  # protoc; run it with SUBSTRATE_PROTO_VERIFY=1 (optionally with
  # SUBSTRATE_SOURCE_DIR and PROTOC) via scripts/generate-substrate-proto.sh.
  # shellcheck source=providers/substrate/nativepb/upstream.env
  source substrate/nativepb/upstream.env
  if command -v sha256sum >/dev/null; then
    digest="$(sha256sum substrate/nativepb/ateapi.proto | awk '{print $1}')"
  else
    digest="$(shasum -a 256 substrate/nativepb/ateapi.proto | awk '{print $1}')"
  fi
  [[ "$digest" == "$SUBSTRATE_UPSTREAM_PROTO_SHA256" ]] || { echo "vendored Substrate protocol differs from the pinned upstream source" >&2; exit 1; }
  grep -qx "// 	protoc-gen-go ${SUBSTRATE_PROTOC_GEN_GO_VERSION}" substrate/nativepb/ateapi.pb.go || { echo "Substrate bindings were not generated by protoc-gen-go ${SUBSTRATE_PROTOC_GEN_GO_VERSION}" >&2; exit 1; }
  grep -qx "// - protoc-gen-go-grpc ${SUBSTRATE_PROTOC_GEN_GO_GRPC_VERSION}" substrate/nativepb/ateapi_grpc.pb.go || { echo "Substrate bindings were not generated by protoc-gen-go-grpc ${SUBSTRATE_PROTOC_GEN_GO_GRPC_VERSION}" >&2; exit 1; }
  grep -qE "^// 	protoc +v[0-9]+\.${SUBSTRATE_PROTOC_VERSION}$" substrate/nativepb/ateapi.pb.go || { echo "Substrate bindings were not generated by protoc ${SUBSTRATE_PROTOC_VERSION}" >&2; exit 1; }
  if [[ "${SUBSTRATE_PROTO_VERIFY:-}" == 1 ]]; then
    bash ../scripts/generate-substrate-proto.sh verify
  fi
fi
